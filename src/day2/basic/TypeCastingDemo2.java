package day2.basic;

public class TypeCastingDemo2 {
    public static void main(String[] args) {
        char c1 = 97;
        short s1 = 97;
        System.out.println(c1);
        System.out.println(s1);

        System.out.println("==============");
        char c2 = 'c';
        short s2 = 'c';
        System.out.println(c2);
        System.out.println(s2);

    }
}
